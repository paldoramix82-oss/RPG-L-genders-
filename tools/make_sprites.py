def preview(sprites, path, scale=4):
    groups = {}
    for (g, n), img in sprites.items():
        groups.setdefault(g, []).append((n, img))
    cell = 34 * scale
    cols = 16
    rows = sum((len(v) + cols - 1) // cols for v in groups.values())
    sheet = Image.new("RGBA", (cols * cell, rows * cell), (58, 52, 70, 255))
    r = 0
    for g, items in groups.items():
        for i, (n, img) in enumerate(items):
            big = img.resize((img.width * scale, img.height * scale), Image.NEAREST)
            x = (i % cols) * cell + (cell - big.width) // 2
            y = (r + i // cols) * cell + (cell - big.height) // 2
            sheet.alpha_composite(big, (x, y))
        r += (len(items) + cols - 1) // cols
    sheet.save(path)


