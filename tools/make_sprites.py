def rgba(hexa, a=255):
    return (int(hexa[0:2], 16), int(hexa[2:4], 16), int(hexa[4:6], 16), a)


def from_ascii(rows, pal=None, outline=True, outline_color="K"):
    pal = dict(PAL, **(pal or {}))
    h = len(rows)
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in (".", " "):
                px[x, y] = rgba(pal[ch])
    if outline:
        add_outline(img, rgba(pal[outline_color]))
    return img


def add_outline(img, color):
    w, h = img.size
    src = img.copy().load()
    px = img.load()
    for y in range(h):
        for x in range(w):
            if src[x, y][3] != 0:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and src[nx, ny][3] != 0 and src[nx, ny][:3] != color[:3]:
                    px[x, y] = color
                    break


class Canvas:
    """Petite toile pour les générateurs (coordonnées entières)."""

    def __init__(self, w=16, h=16):
        self.w, self.h = w, h
        self.px = {}

    def put(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h and ch:
            self.px[(x, y)] = ch

    def get(self, x, y):
        return self.px.get((x, y))

    def rows(self):
        return ["".join(self.px.get((x, y), ".") for x in range(self.w)) for y in range(self.h)]

    def image(self, outline=True, pal=None):
        return from_ascii(self.rows(), pal, outline)


