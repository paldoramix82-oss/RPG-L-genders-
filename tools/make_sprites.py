def bush(seed, leaf, berries=None, size=16):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    ramp = [shade(leaf, -0.5), shade(leaf, -0.25), leaf, shade(leaf, 0.3)]
    blobs = [(8 + rnd.uniform(-3, 3), 9 + rnd.uniform(-1, 2), rnd.uniform(3.5, 5)) for _ in range(4)]
    for y in range(size):
        for x in range(size):
            best = None
            for bx, by, br in blobs:
                d = math.hypot(x - bx, y - by)
                if d <= br:
                    v = -((x - bx) / br * -0.6 + (y - by) / br * -0.8) + rnd.uniform(-0.3, 0.3)
                    best = v if best is None else max(best, v)
            if best is not None:
                px[x, y] = rgba(ramp[3 if best > 0.5 else (2 if best > 0 else (1 if best > -0.5 else 0))])
    if berries:
        for _ in range(5):
            x, y = rnd.randint(4, 11), rnd.randint(5, 12)
            if px[x, y][3]:
                px[x, y] = rgba(berries)
    add_outline(img, rgba(shade(leaf, -0.75)))
    return img


def rock(seed, base="8a8478", size=16, big=False):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    ramp = [shade(base, -0.45), shade(base, -0.2), base, shade(base, 0.25), shade(base, 0.45)]
    r = 6.5 if big else 4.5
    pts = []
    for i in range(9):
        a = i / 9 * math.tau
        rr = r * rnd.uniform(0.8, 1.15)
        pts.append((size / 2 + math.cos(a) * rr * 1.15, size * 0.58 + math.sin(a) * rr * 0.85))

    def inside(x, y):
        n = len(pts)
        ok = False
        j = n - 1
        for i in range(n):
            xi, yi = pts[i]
            xj, yj = pts[j]
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                ok = not ok
            j = i
        return ok

    for y in range(size):
        for x in range(size):
            if inside(x + 0.5, y + 0.5):
                nx = (x - size / 2) / r
                ny = (y - size * 0.5) / r
                v = -(nx * -0.6 + ny * -0.9) + rnd.uniform(-0.15, 0.15)
                px[x, y] = rgba(ramp[4 if v > 0.8 else (3 if v > 0.25 else (2 if v > -0.3 else 1))])
    # quelques fissures et mousse
    for _ in range(2 if big else 1):
        x, y = rnd.randint(5, 10), rnd.randint(8, 11)
        if px[x, y][3]:
            px[x, y] = rgba(ramp[0])
    add_outline(img, rgba(shade(base, -0.7)))
    return img


