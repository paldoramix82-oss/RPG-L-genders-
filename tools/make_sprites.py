def D(t):
    return 14 - t, 1 + t


def blade(c, t0, t1, light="w", mid="m", dark="M"):
    for t in range(t0, t1):
        x, y = D(t)
        c.put(x, y, mid)
        if t > t0:
            c.put(x - 1, y, light)
            c.put(x, y + 1, dark)


def haft(c, t0, t1, light="E", dark="d"):
    for t in range(t0, t1):
        x, y = D(t)
        c.put(x, y, light)
        c.put(x, y + 1, dark)


def cross(c, t, k, cols=("y", "Y", "o")):
    x, y = D(t)
    for i in range(-k, k + 1):
        col = cols[0] if i < 0 else (cols[1] if i == 0 else cols[2])
        c.put(x + i, y + i, col)


def weapon(kind):
    c = Canvas()
    if kind in ("sword", "dagger", "rapier"):
        start = {"sword": 0, "dagger": 4, "rapier": 0}[kind]
        guard = {"sword": 9, "dagger": 9, "rapier": 10}[kind]
        if kind == "rapier":
            for t in range(start, guard):
                x, y = D(t)
                c.put(x, y, "m" if t % 3 else "w")
        else:
            blade(c, start, guard)
        cross(c, guard, 2 if kind != "dagger" else 1)
        if kind == "rapier":
            x, y = D(guard + 1)
            for p in ((x - 2, y), (x - 2, y - 1), (x - 1, y - 2), (x, y - 2)):
                c.put(*p, "Y")
        haft(c, guard + 1, guard + 3, "L", "d")
        x, y = D(guard + 3)
        c.put(x, y, "Y")
        c.put(x, y + 1, "o")
    elif kind == "axe":
        haft(c, 2, 14)
        for t, k in ((1, 2), (2, 3), (3, 4), (4, 4), (5, 3), (6, 2)):
            x, y = D(t)
            for i in range(1, k + 1):
                col = "w" if i == k else ("m" if i > 1 else "M")
                c.put(x - i, y - i, col)
                c.put(x - i, y - i + 1, col if i < k else "m")
        x, y = D(3)
        c.put(x + 1, y + 1, "n")
        c.put(x + 2, y + 2, "n")
    elif kind == "hammer":
        haft(c, 4, 14)
        for t in range(1, 5):
            x, y = D(t)
            for i in range(-3, 4):
                c.put(x + i, y + i, "w" if i < -1 else ("m" if i < 2 else "M"))
            for i in range(-3, 4):
                c.put(x + i + 1, y + i, "M" if t == 4 else "m")
    elif kind == "mace":
        haft(c, 4, 14)
        cx, cy = D(2)
        for dy in range(-2, 3):
            for dx in range(-2, 3):
                if dx * dx + dy * dy <= 5:
                    c.put(cx + dx, cy + dy, "w" if dx + dy < -1 else ("m" if dx + dy < 2 else "M"))
        for dx, dy in ((0, -3), (3, 0), (-3, 0), (0, 3), (2, -2), (-2, 2)):
            c.put(cx + dx, cy + dy, "n")
    elif kind == "spear":
        haft(c, 4, 15)
        for t in range(0, 4):
            x, y = D(t)
            c.put(x, y, "m")
            if 0 < t < 3:
                c.put(x - 1, y, "w")
                c.put(x, y + 1, "M")
        x, y = D(4)
        c.put(x - 1, y + 1, "R")
        c.put(x - 2, y + 2, "q")
    elif kind == "staff":
        haft(c, 3, 15)
        x, y = D(2)
        for p, col in (((x, y), "E"), ((x + 1, y - 1), "E"), ((x + 1, y - 2), "E"), ((x, y - 3), "e"), ((x - 1, y - 3), "e"), ((x - 2, y - 2), "E")):
            c.put(*p, col)
        c.put(x - 1, y - 1, "B")
        c.put(x, y - 2, "b")
        c.put(x - 1, y - 2, "b")
        c.put(x, y - 1, "B")
    elif kind == "wand":
        for t in range(5, 13):
            x, y = D(t)
            c.put(x, y, "y" if t < 7 else ("i" if t < 11 else "P"))
        x, y = D(4)
        for dx, dy, col in ((0, 0, "h"), (1, 0, "y"), (-1, 0, "y"), (0, 1, "y"), (0, -1, "y"), (1, -1, "f"), (-1, 1, "f")):
            c.put(x + dx, y + dy, col)
    return c.image()


